#!/usr/bin/env python3
"""Draw the console screenshot's block model to a PNG.

The SVG that `console_shot.mjs` writes needs a rasteriser this environment does
not have (no librsvg, no cairo, no headless browser), so the committed PNG is
drawn here, from the same block model, with Pillow. The blocks are the renderer's
own output — text and order — so the picture cannot say anything the page would
not.

    python scripts/console_shot.py --blocks empty.json --out ../docs/console/empty-window.png

Pillow is a dev-extras dependency (not runtime): the tests assert the text, and the
PNG is a review artifact regenerated by hand (KNOWN_GAPS §30 records why).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
BLACK = (17, 24, 39)
GREY = (107, 114, 128)
BODY = (75, 85, 99)
RULE = (229, 231, 235)


def _font(name: str, size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(str(FONT_DIR / name), size)


def draw(blocks: list[dict[str, Any]], width: int, out: Path) -> None:
    regular, bold = "DejaVuSans.ttf", "DejaVuSans-Bold.ttf"
    line_height = 22
    # Two passes: measure, then draw. Simpler than a virtual canvas, and the
    # height has to be known before the image exists.
    height = 96
    for block in blocks:
        if block["kind"] in {"title", "header"} or block["kind"] == "row":
            height += 46
        else:
            height += line_height * max(1, len(_wrap(block["text"], 96))) + 12

    image = Image.new("RGB", (width, height), "white")
    canvas = ImageDraw.Draw(image)
    canvas.text((32, 28), "Adapt console", font=_font(bold, 26), fill=BLACK)
    canvas.text(
        (32, 62),
        "rendered from the console's own renderer; every value traces to an endpoint",
        font=_font(regular, 13),
        fill=GREY,
    )

    y = 104
    for block in blocks:
        if block["kind"] == "header":
            canvas.text((32, y), block["text"], font=_font(bold, 12), fill=BLACK)
            y += 22
        elif block["kind"] == "title":
            canvas.line([(20, y), (width - 20, y)], fill=RULE)
            canvas.text((32, y + 12), block["text"], font=_font(bold, 17), fill=BLACK)
            y += 46
        elif block["kind"] == "row":
            canvas.text((32, y), block["label"], font=_font(regular, 13), fill=GREY)
            canvas.text((32, y + 18), block["text"], font=_font(bold, 15), fill=BLACK)
            y += 46
        else:
            for line in _wrap(block["text"], 96):
                canvas.text((32, y), line, font=_font(regular, 13), fill=BODY)
                y += line_height
            y += 12

    image.save(out)


def _wrap(text: str, width: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for word in words:
        candidate = f"{line} {word}".strip()
        if len(candidate) > width:
            lines.append(line)
            line = word
        else:
            line = candidate
    return [*lines, line] if line else lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blocks", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    payload = json.loads(Path(args.blocks).read_text())
    draw(payload["blocks"], payload["width"], Path(args.out))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
