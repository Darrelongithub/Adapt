#!/usr/bin/env python3
"""Draw the console screenshot's block model to a PNG.

The SVG that `console_shot.mjs` writes needs a rasteriser this environment does
not have (no librsvg, no cairo, no headless browser), so the committed PNG is
drawn here, from the same block model, with Pillow. The blocks are the renderer's
own output — text, order, and now the style each block resolved to — so the
picture cannot say anything the page would not.

    python scripts/console_shot.py --blocks empty.json --out ../docs/console/empty-window.png

The palette is **not** kept here. `CONSOLE_STYLE.md` §6 gate 4: this script parses
`:root` out of `console/styles.css` exactly as the `.mjs` does, so there is one
copy of every hex in the repository and it is the stylesheet's.

Italics are synthesised by shear: this image has no italic face installed
(DejaVu ships regular and bold only) and a browser would synthesise the oblique
too, so the nudged glyphs are the same compromise the screen makes.

Pillow is a dev-extras dependency (not runtime): the tests assert the text, and the
PNG is a review artifact regenerated by hand (KNOWN_GAPS §30 records why).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
FACES = {
    ("sans", 400): "DejaVuSans.ttf",
    ("sans", 600): "DejaVuSans-Bold.ttf",
    ("sans", 700): "DejaVuSans-Bold.ttf",
    ("serif", 400): "DejaVuSerif.ttf",
    ("serif", 600): "DejaVuSerif-Bold.ttf",
    ("serif", 700): "DejaVuSerif-Bold.ttf",
}
SCALE = 2  # drawn at 2x and downsampled: 13px text at 1x is mush
SHEAR = 0.21  # the oblique angle a browser would synthesise
DEFAULT_STYLES = Path(__file__).resolve().parents[1] / "src/adapt_engine/console/styles.css"

#: Filled from `:root` by `main()`; module-level so the drawing helpers can read it.
TOKENS: dict[str, str] = {}


# --------------------------------------------------------------------- palette


def parse_root(styles: Path) -> dict[str, str]:
    """`--token: #hex;` pairs from every `:root` block in the stylesheet."""
    css = re.sub(r"/\*.*?\*/", "", styles.read_text(encoding="utf-8"), flags=re.S)
    tokens: dict[str, str] = {}
    for block in re.findall(r":root\s*\{([^}]*)\}", css):
        for decl in block.split(";"):
            if ":" not in decl:
                continue
            name, value = decl.split(":", 1)
            tokens[name.strip()] = value.strip()
    if not tokens:
        raise SystemExit(f"no :root tokens in {styles}")
    return tokens


def rgb(token: str) -> tuple[int, int, int]:
    """`var(--x)`, a short or long hex, or `rgb()` to a Pillow colour.

    Written without a hex example on purpose: `CONSOLE_STYLE.md` §6 gate 1 greps
    every shipped file for a hex literal, and a docstring is a shipped file.
    """
    value = token.strip()
    if value.startswith("--"):  # a bare token name is a token, not an rgb() string
        value = f"var({value})"
    for _ in range(8):  # resolve var() chains, however they were nested
        match = re.fullmatch(r"var\(\s*(--[\w-]+)\s*\)", value)
        if not match:
            break
        value = TOKENS[match.group(1)]
    if value.startswith("#"):
        digits = value[1:]
        if len(digits) == 3:
            digits = "".join(ch * 2 for ch in digits)
        return tuple(int(digits[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]
    numbers = [int(n) for n in re.findall(r"\d+", value)]
    return (numbers[0], numbers[1], numbers[2])


def rgba(token: str) -> tuple[int, int, int, int]:
    return (*rgb(token), 255)


def colour(block: dict[str, Any], key: str = "color") -> tuple[int, int, int]:
    return rgb(str(block.get(key) or TOKENS["--ink"]))


# ----------------------------------------------------------------------- fonts


def face(style: dict[str, Any], size: float) -> ImageFont.FreeTypeFont:
    family = style.get("family") or "sans"
    weight = int(style.get("weight") or 400)
    bucket = 700 if weight >= 700 else 600 if weight >= 600 else 400
    name = FACES.get((family, bucket), FACES[("sans", 400)])
    return ImageFont.truetype(str(FONT_DIR / name), max(6, round(size * SCALE)))


def measure(text: str, style: dict[str, Any]) -> tuple[int, int]:
    font = face(style, style.get("size") or 13)
    left, top, right, bottom = font.getbbox(text)
    return int(right - left), int(bottom - top)


def wrap(text: str, style: dict[str, Any], width: int) -> list[str]:
    words, lines, line = str(text).split(), [], ""
    for word in words:
        candidate = f"{line} {word}".strip()
        if measure(candidate, style)[0] > width and line:
            lines.append(line)
            line = word
        else:
            line = candidate
    if line:
        lines.append(line)  # the tail: the loop only flushes on overflow
    return lines or [""]


def draw_text(
    canvas: Image.Image,
    xy: tuple[float, float],
    text: str,
    style: dict[str, Any],
    width: int | None = None,
) -> int:
    """Draw one run of text, italic-sheared if the style says so. Returns height."""
    font = face(style, style.get("size") or 13)
    fill = colour(style)
    lines = wrap(text, style, width) if width else [str(text)]
    line_height = round((style.get("size") or 13) * 1.55 * SCALE)
    top = xy[1]
    for line in lines:
        if style.get("italic"):
            _shear(canvas, (xy[0], top), line, font, fill)
        else:
            ImageDraw.Draw(canvas).text((xy[0], top), line, font=font, fill=fill)
        top += line_height
    return int(top - xy[1])


def _shear(
    canvas: Image.Image,
    xy: tuple[float, float],
    text: str,
    font: ImageFont.FreeTypeFont,
    fill: tuple[int, int, int],
) -> None:
    """Paste `text` through an affine shear — the italic no font here provides."""
    left, top, right, bottom = (int(v) for v in font.getbbox(text))
    width, height = right - left + 4, bottom - top + 4
    layer = Image.new("RGBA", (width + int(height * SHEAR) + 4, height), (0, 0, 0, 0))
    ImageDraw.Draw(layer).text((2 - left, 2 - top), text, font=font, fill=(*fill, 255))
    skewed = layer.transform(
        layer.size,
        Image.Transform.AFFINE,
        (1, SHEAR, -SHEAR * height, 0, 1, 0),
        resample=Image.Resampling.BICUBIC,
    )
    canvas.alpha_composite(skewed, (int(xy[0]), int(xy[1])))


# ---------------------------------------------------------------------- layout

LEFT = 48
VALUE_X = 348
RULE_INSET = 24


def plan(blocks: list[dict[str, Any]], heading: dict[str, str], width: int) -> list[dict[str, Any]]:
    """Measure every block before anything is drawn: the height comes first."""
    placed: list[dict[str, Any]] = []
    y = 56.0 * SCALE
    h1 = {"family": "serif", "size": 26, "weight": 700}
    sub = {"family": "sans", "size": 13, "weight": 400}
    placed.append({"kind": "h1", "text": heading["title"], "style": h1, "y": y})
    y += 34 * SCALE
    placed.append({"kind": "rule", "y": y, "thickness": 2, "width": 196 * SCALE})
    y += 18 * SCALE
    placed.append({"kind": "h1", "text": heading["subtitle"], "style": sub, "y": y})
    y += 40 * SCALE

    for block in blocks:
        kind = block["kind"]
        style = block.get("style") or {}
        if kind == "title":
            y += 16 * SCALE
            placed.append({"kind": "hairline", "y": y})
            y += 12 * SCALE
            placed.append(
                {
                    "kind": "title",
                    "text": str(block["text"]).upper(),
                    "style": style,
                    "y": y,
                }
            )
            y += 30 * SCALE
        elif kind == "row":
            placed.append(
                {
                    "kind": "row",
                    "label": block.get("label") or "",
                    "labelStyle": block.get("labelStyle") or style,
                    "text": block.get("text") or "",
                    "style": style,
                    "y": y,
                }
            )
            y += 24 * SCALE
        elif kind == "sentence":
            lines = wrap(block["text"], style, (width - 2 * LEFT) * SCALE)
            placed.append({"kind": "sentence", "lines": lines, "style": style, "y": y})
            y += len(lines) * (style.get("size") or 13) * 1.55 * SCALE + 10 * SCALE
        elif kind == "table":
            header = block.get("header") or []
            rows = block.get("rows") or []
            columns = max(0, len(header), *(len(row) for row in rows))
            widths = []
            for column in range(columns):
                cells = (header[column : column + 1] if len(header) > column else []) + [
                    row[column] for row in rows if len(row) > column
                ]
                widest = max((measure(cell["text"].upper(), style)[0] for cell in cells), default=0)
                widths.append(max(widest + 24 * SCALE, 48 * SCALE))
            available = (width - 2 * LEFT) * SCALE
            total = sum(widths) or 1
            fitted = [w * available / total for w in widths] if total > available else widths
            column_x: list[float] = []
            x = float(LEFT * SCALE)
            for column_width in fitted:
                column_x.append(x)
                x += column_width
            placed.append(
                {
                    "kind": "table",
                    "header": header,
                    "rows": rows,
                    "columnX": column_x,
                    "widths": fitted,
                    "style": style,
                    "y": y,
                }
            )
            y += (26 * SCALE if header else 0) + sum(34 * SCALE for _ in rows) + 8 * SCALE
    placed.append({"kind": "end", "y": y + 40 * SCALE})
    return placed


def _draw_table(
    canvas: Image.Image, paint: ImageDraw.ImageDraw, item: dict[str, Any], width: int
) -> None:
    """Header band, one line per row, a hairline under each: no vertical rules."""
    top = item["y"]
    rule = rgba(TOKENS["--rule"])

    def row(
        cells: list[dict[str, Any]], height: int, fill: str | None, upper: bool = False
    ) -> None:
        if fill:
            paint.rectangle(
                (
                    LEFT * SCALE - 12 * SCALE,
                    top - 6 * SCALE,
                    width * SCALE - LEFT * SCALE,
                    top + height,
                ),
                fill=rgba(fill),
            )
        for index, cell in enumerate(cells):
            style = cell.get("style") or item["style"]
            cursor = item["columnX"][index]
            for run in cell.get("runs") or [{"text": cell["text"], "style": style}]:
                run_style = run.get("style") or style
                text = str(run["text"]).upper() if upper else str(run["text"])
                run_width = measure(text, run_style)[0] + 16 * SCALE
                if run_style.get("background"):
                    paint.rectangle(
                        (cursor, top - 6 * SCALE, cursor + run_width, top + 22 * SCALE),
                        fill=rgba(run_style["background"]),
                    )
                if run_style.get("borderLeft"):
                    paint.rectangle(
                        (cursor, top - 6 * SCALE, cursor + 2 * SCALE, top + 22 * SCALE),
                        fill=rgba(run_style["borderLeft"]),
                    )
                draw_text(
                    canvas,
                    (cursor + (8 * SCALE if run_style.get("background") else 0), top),
                    text,
                    run_style,
                )
                cursor += run_width + 4 * SCALE

    if item["header"]:
        row(item["header"], 22 * SCALE, "--surface-sunk", True)
        top += 26 * SCALE
    for cells in item["rows"]:
        row(cells, 22 * SCALE, None)
        paint.rectangle(
            (LEFT * SCALE, top + 16 * SCALE, width * SCALE - LEFT * SCALE, top + 17 * SCALE),
            fill=rule,
        )
        top += 34 * SCALE


def draw(blocks: list[dict[str, Any]], heading: dict[str, str], width: int, out: Path) -> None:
    placed = plan(blocks, heading, width)
    end = next(item for item in placed if item["kind"] == "end")
    height = int(end["y"])
    canvas = Image.new("RGBA", (width * SCALE, height), rgba(TOKENS["--bg"]))
    paint = ImageDraw.Draw(canvas)

    # The card: one --surface rectangle with a hairline, no shadow (§5).
    paint.rectangle(
        (RULE_INSET * SCALE, 12 * SCALE, width * SCALE - RULE_INSET * SCALE, height - 12 * SCALE),
        fill=rgba(TOKENS["--surface"]),
        outline=rgba(TOKENS["--rule"]),
    )

    for item in placed:
        kind = item["kind"]
        if kind == "h1":
            draw_text(canvas, (LEFT * SCALE, item["y"]), item["text"], item["style"])
        elif kind == "rule":
            paint.rectangle(
                (
                    LEFT * SCALE,
                    item["y"],
                    LEFT * SCALE + item["width"],
                    item["y"] + item["thickness"] * SCALE,
                ),
                fill=rgba(TOKENS["--accent"]),
            )
        elif kind == "hairline":
            paint.rectangle(
                (
                    (LEFT - 24) * SCALE,
                    item["y"],
                    width * SCALE - (LEFT - 24) * SCALE,
                    item["y"] + SCALE,
                ),
                fill=rgba(TOKENS["--rule"]),
            )
        elif kind == "title":
            draw_text(canvas, (LEFT * SCALE, item["y"]), item["text"], item["style"])
        elif kind == "row":
            draw_text(canvas, (LEFT * SCALE, item["y"]), item["label"], item["labelStyle"])
            label_width = measure(item["label"], item["labelStyle"])[0]
            x = max(VALUE_X * SCALE, LEFT * SCALE + label_width + 24 * SCALE)
            draw_text(canvas, (x, item["y"]), item["text"], item["style"])
        elif kind == "sentence":
            top = item["y"]
            for line in item["lines"]:
                draw_text(canvas, (LEFT * SCALE, top), line, item["style"])
                top += (item["style"].get("size") or 13) * 1.55 * SCALE
        elif kind == "table":
            _draw_table(canvas, paint, item, width)

    canvas.convert("RGB").resize((width, int(height / SCALE)), Image.Resampling.LANCZOS).save(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blocks", required=True, help="the renderer's block model (JSON)")
    parser.add_argument("--out", required=True, help="PNG to write")
    parser.add_argument(
        "--styles", default=str(DEFAULT_STYLES), help="stylesheet to read :root from"
    )
    args = parser.parse_args()

    global TOKENS
    TOKENS = parse_root(Path(args.styles))
    model = json.loads(Path(args.blocks).read_text(encoding="utf-8"))
    heading = model.get("heading") or {"title": "Adapt console", "subtitle": ""}
    draw(model["blocks"], heading, int(model.get("width") or 1180), Path(args.out))


if __name__ == "__main__":
    main()
